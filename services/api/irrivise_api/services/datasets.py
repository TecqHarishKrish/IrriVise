SAMPLE_FILE = "synthetic_weather_tn_v1.csv"
SAMPLE_NAME = "Synthetic demonstration weather (Tamil Nadu-like, 2004–2023)"
SAMPLE_PROVENANCE = {
    "label": "SYNTHETIC DEMONSTRATION — not historical weather, not field measurements",
    "generator": "irrivise_core.data.synthetic.generate_synthetic_weather (synthetic-tn-v1, seed 42)",
    "regenerate": "python scripts/sample_data.py --check",
}


def dataset_dict(d: WeatherDataset) -> dict:
    return {"id": d.id, "name": d.name, "source": d.source, "rows": d.rows, "start": d.start_date, "end": d.end_date,
            "latitude": d.latitude, "longitude": d.longitude, "time_standard": d.time_standard, "checksum_sha256": d.checksum_sha256,
            "units": json.loads(d.units_json), "validation": json.loads(d.validation_json), "provenance": json.loads(d.provenance_json),
            "license": d.license, "created_at": d.created_at.isoformat() + "Z", "is_synthetic": d.source == "sample"}


def ensure_sample(session: Session) -> WeatherDataset:
    """Register the committed synthetic fixture (idempotent; verifies checksum)."""
    source = REPO_ROOT / "data" / "sample" / SAMPLE_FILE
    if not source.is_file():
        raise ApiError(500, "sample_missing", "Sample dataset file is missing; run python scripts/sample_data.py")
    target = safe_join("data", "sample", SAMPLE_FILE)
    if target != source.resolve():
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or sha256_file(target) != sha256_file(source):
            shutil.copyfile(source, target)
    checksum = sha256_file(target)
    existing = session.scalar(select(WeatherDataset).where(WeatherDataset.source == "sample", WeatherDataset.checksum_sha256 == checksum))
    if existing:
        if existing.archived:
            existing.archived = False
        return existing
    frame, report = read_weather_csv(target)
    record = WeatherDataset(id=new_id(), name=SAMPLE_NAME, source="sample", file_path=relative(target), checksum_sha256=checksum,
                            rows=len(frame), start_date=report.start, end_date=report.end, latitude=10.79, longitude=78.70,
                            time_standard="synthetic (no time standard)", units_json=json.dumps(UNITS),
                            validation_json=json.dumps(report.as_dict()), provenance_json=json.dumps(SAMPLE_PROVENANCE),
                            license="Generated by this repository; free to use.")
    session.add(record)
    session.flush()
    return record


def import_csv(session: Session, name: str, text: str, latitude: float | None, longitude: float | None) -> WeatherDataset:
    try:
        frame, report = read_weather_csv(text=text)
    except WeatherValidationError as exc:
        raise ApiError(422, "invalid_weather_csv", str(exc), exc.report.as_dict() if exc.report else None) from exc
    dataset_id = new_id()
    path = safe_join("data", "processed", f"upload-{dataset_id}.csv")
    write_weather_csv(frame, path)
    record = WeatherDataset(id=dataset_id, name=name, source="uploaded", file_path=relative(path), checksum_sha256=sha256_file(path),
                            rows=len(frame), start_date=report.start, end_date=report.end, latitude=latitude, longitude=longitude,
                            time_standard="as supplied by uploader (unknown)", units_json=json.dumps(UNITS),
                            validation_json=json.dumps(report.as_dict()),
                            provenance_json=json.dumps({"label": "User-uploaded CSV; provenance asserted by uploader", "original_rows": report.rows}),
                            license="Supplied by user")
    session.add(record)
    session.flush()
    return record


def get_dataset(session: Session, dataset_id: str) -> WeatherDataset:
    d = session.get(WeatherDataset, dataset_id)
    if not d or d.archived:
        raise not_found("Dataset")
    return d


@lru_cache(maxsize=16)
def _load(path: str, checksum: str) -> pd.DataFrame:
    full = safe_join(*path.split("/"))
    if sha256_file(full) != checksum:
        raise ApiError(409, "dataset_checksum_mismatch", "Dataset file changed on disk since import; re-import it")
    frame, _ = read_weather_csv(full)
    return frame


def load_frame(d: WeatherDataset) -> pd.DataFrame:
    return _load(d.file_path, d.checksum_sha256)


def seasons_for(d: WeatherDataset, planting_mmdd: str, length: int):
    frame = load_frame(d)
    seasons, skipped = extract_seasons(frame, planting_mmdd, length)
    split = chronological_split([s.season_id for s in seasons])
    return seasons, skipped, split


def forecaster_for(seasons, split) -> ClimatologyForecaster:
    train = [s for s in seasons if s.season_id in split.train]
    return ClimatologyForecaster(train)


def preview(d: WeatherDataset, planting_mmdd: str = "06-15", length: int = 140, max_points: int = 400) -> dict:
    frame = load_frame(d)
    seasons, skipped, split = seasons_for(d, planting_mmdd, length)
    yearly = frame.assign(year=pd.to_datetime(frame["date"]).dt.year).groupby("year").agg(
        rain_mm=("rain_mm", "sum"), eto_mm=("eto_mm", "sum"), days=("rain_mm", "size")).reset_index()
    season_totals = [{"season_id": s.season_id, "start": s.start, "rain_mm": round(float(s.rain_mm.sum()), 2),
                      "eto_mm": round(float(s.eto_mm.sum()), 2),
                      "split": "train" if s.season_id in split.train else "validation" if s.season_id in split.validation else "test"}
                     for s in seasons]
    return {"dataset": dataset_dict(d), "series": preview_frame(frame, max_points), "series_decimated": len(frame) > max_points,
            "yearly_totals": yearly.round(2).to_dict(orient="records"), "seasons": season_totals, "skipped_seasons": skipped,
            "split": split.as_dict(), "planting_mmdd": planting_mmdd, "season_length_days": length,
            "head": preview_frame(frame.head(10), 10)}
